class Settings:
    """Build settings collected from $Configuration and $Project blocks."""

    def __init__(self):
        self.sources = []
        self.headers = []
        self.ignored = OrderedDict()      # ext -> [paths]
        self.dynamic = []
        self.includes = []
        self.defines = []
        self.libs = []                    # in-tree project libs (target names)
        self.system_libs = []             # -l<name>
        self.dropped_libs = []            # Windows libs / prebuilts, for the audit
        self.link_scripts = []            # *.link inputs needing a real link step
        self.flags = []                   # GCC_Extra* / AdditionalOptions
        self.commands = []                # $CommandLine
        self.pch_through = None
        self.output_name = None
        self.game_output_file = None
        self.config_type = None
        self.is_lib = False

    def add_unique(self, seq, value):
        if value and value not in seq:
            seq.append(value)

    def merge_sources(self, other):
        for s in other.sources:
            self.add_unique(self.sources, s)
        for s in other.dynamic:
            self.add_unique(self.dynamic, s)
        for ext, lst in other.ignored.items():
            for p in lst:
                self.ignored.setdefault(ext, []).append(p)

    def to_dict(self):
        return {
            "sources": sorted(set(self.sources)),
            "headers": sorted(set(self.headers)),
            "dynamic": sorted(set(self.dynamic)),
            "ignored_exts": {k: sorted(set(v)) for k, v in self.ignored.items()},
            "includes": sorted(set(self.includes)),
            "defines": sorted(set(self.defines)),
            "libs": sorted(set(self.libs)),
            "system_libs": sorted(set(self.system_libs)),
            "dropped_libs": sorted(set(self.dropped_libs)),
            "link_scripts": sorted(set(self.link_scripts)),
            "flags": sorted(set(self.flags)),
            "commands": self.commands,
            "pch_through": self.pch_through,
            "output_name": self.output_name,
            "game_output_file": self.game_output_file,
            "config_type": self.config_type,
            "is_lib": self.is_lib,
        }


class Module:
    def __init__(self, name, path):
        self.name = name            # VPC project label, as written in the .vpc
        self.target = target_name(name)   # sanitised CMake target name
        self.path = path
        self.settings = Settings()

    def to_dict(self):
        d = {"name": self.name, "target": self.target, "vpc": self.path}
        d.update(self.settings.to_dict())
        return d


# --------------------------------------------------------------------------
# Library-ness resolution (ordered $Include closure, last $ConfigurationType wins)
# --------------------------------------------------------------------------
def detect_config_type(path, symbols, root, seen=None, depth=0, ctx=None):
    """Return (config_type, is_lib) for a .vpc root.

    The base script sets "$ConfigurationType Application (.exe)" for every
    project, so scanning for 'any library type' would be wrong in both
    directions. VPC semantics are "later wins", so this walks the $Include
    closure in file order and keeps the last type it sees.
    """
    if seen is None:
        seen = set()
    real = os.path.realpath(path)
    if real in seen or depth > 24 or not os.path.isfile(real):
        return None, None
    seen.add(real)
    base = os.path.dirname(real)
    text = strip_comments(open(real, encoding="utf-8", errors="replace").read())
    directives = RawParser(text, real).parse_block(False)
    if ctx is None:
        ctx = Context(symbols, root)
        # Seed SRCDIR with this script's directory, then let "$Macro SRCDIR ..."
        # in the root script override it. It must NOT be re-seeded per level:
        # SRCDIR means the *source root* for the whole include chain, and
        # re-deriving it per file yields "vpc_scripts/vpc_scripts/...".
        ctx.macros["SRCDIR"] = base

    ctype = None
    for d in directives:
        if d.name in ("Macro", "MacroRequired", "MacroRequiredAllowEmpty"):
            ctx.define_macro(d, base)
        elif d.name == "Include" and ctx.eval_cond(d.cond):
            for inc in d.active(ctx):
                ip = norm_vpc_path(ctx.expand(inc), base, root)
                if not ip.startswith("/"):
                    ip = os.path.join(root, ip)
                sub, _ = detect_config_type(ip, symbols, root, seen, depth + 1, ctx)
                if sub:
                    ctype = sub
        elif d.name == "Configuration" and ctx.eval_cond(d.cond):
            sub = find_config_type(d.block)
            if sub:
                ctype = ctx.expand(sub[0])
    if ctype is None:
        return None, None
    return ctype, "library" in ctype.lower()


def find_config_type(block):
    """Depth-first search for $ConfigurationType inside a configuration block."""
    for d in block or []:
        if d.name == "ConfigurationType" and d.value and not d.excluded:
            return d.value
        if d.block:
            got = find_config_type(d.block)
            if got:
                return got
    return None


