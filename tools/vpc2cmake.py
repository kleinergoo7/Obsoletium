# Macro expansion + condition evaluation
# --------------------------------------------------------------------------
PATH_MACROS = frozenset([
    "SRCDIR", "LIBPUBLIC", "OUTBINDIR", "OUTAPPBINDIR", "OUTDIR",
    "CLIENTDIR", "GAMEDIR", "PLATSUBDIR",
])


# VPC conditional expression tokens. Order matters: the long forms and the
# operators are tried before the bare-identifier fallback.
_COND_TOKEN = re.compile(
    r"\$\((?P<paren>[A-Za-z_][A-Za-z0-9_]*)\)"
    r"|\$(?P<dollar>[A-Za-z_][A-Za-z0-9_]*)"
    r"|\b(?P<kw>and|or|not)\b"
    r"|(?P<op>&&|\|\||!|\(|\))"
    r"|\b(?P<bare_name>[A-Za-z_][A-Za-z0-9_]*)\b"
    r"|(?P<ws>\s+)"
)


class Context:
    def __init__(self, symbols, root):
        self.symbols = dict(symbols)
        self.root = root
        # A fresh Context per .vpc root. Sharing one across the whole tree let
        # macros leak between unrelated .vpc files, so e.g. SRCDIR from a
        # sibling module could silently resolve another module's paths.
        self.macros = dict(GENSYM_DEFAULTS)
        self.macros["ROOTSCRIPT"] = ""
        self.macros["SRCDIR"] = root
        # Keys a .vpc script defined itself. Pre-seeded defaults must stay
        # overridable: "$Macro SRCDIR .."" in tier0.vpc has to win over our
        # seed, otherwise every "$SRCDIR\vpc_scripts\..." include misses.
        self.defined = set()
        self.missing_macros = []

    def define(self, key, value, base=None):
        # SRCDIR and friends are declared as relative paths ("..", "..\\..")
        # but stay in scope for the whole $Include chain. Resolving them lazily
        # against whichever file we happen to be in walks the chain out of the
        # repository, so pin them to absolute paths when they are defined.
        if base is not None and value and not value.startswith(("/", "$", "(")):
            if key in PATH_MACROS:
                # VPC mixes separators: "$SRCDIR\\lib\\public$PLATSUBDIR"
                # expands to "<abs>\\lib\\public/linux64". Normalise before
                # using it, or isabs()/join() misread the whole thing.
                value = value.replace("\\", "/")
                if not os.path.isabs(value):
                    value = os.path.normpath(os.path.join(base, value))
        self.macros[key] = value
        self.defined.add(key)

    def define_macro(self, d, base):
        """Apply one $Macro / $MacroRequired / $MacroRequiredAllowEmpty.

        VPC semantics differ by directive and conflating them corrupts the
        include chain:
          $Macro                       last definition wins
          $MacroRequired               first definition wins
          $MacroRequired "X"  (no value)  asserts X is already set -- a
                                       no-op, never an assignment to ""
        """
        if not d.value:
            return
        # "$Macro PLATSUBDIR \"\\osx64\" [$OSX64]" -- the condition decides
        # which platform line wins, so it must be evaluated before assigning.
        if not self.eval_cond(d.cond):
            return
        # A guard on a macro binds to its value argument, so a false one drops
        # the value and leaves the name with nothing to assign.
        vals = d.active(self)
        if len(vals) < 2:
            return
        key = vals[0].upper()
        required = d.name != "Macro"
        raw = vals[1]
        if required:
            if key in self.defined:
                return
            if not raw and key in self.macros:
                return
        self.define(key, self.expand(raw) if raw else "", base)

    def child(self):
        c = Context(self.symbols, self.root)
        c.macros = dict(self.macros)
        c.defined = set(self.defined)
        c.missing_macros = self.missing_macros
        return c

    def expand(self, text, depth=0):
        if depth > 24 or not text:
            return text
        out = text
        # $(Var) and $VAR forms
        def rep(m):
            name = m.group(1) or m.group(2)
            key = name.upper()
            if key in self.macros:
                return str(self.macros[key])
            if key in self.symbols:
                return str(self.macros.get(key, ""))
            self.missing_macros.append(key)
            return m.group(0)

        out = re.sub(r"\$\(([A-Za-z_][A-Za-z0-9_]*)\)|\$([A-Za-z_][A-Za-z0-9_]*)", rep, out)
        if out == text:
            return out
        return self.expand(out, depth + 1)

    def truthy(self, name):
        key = name.upper()
        if key in self.symbols:
            return bool(int(self.symbols[key]))
        if key in self.macros:
            v = str(self.macros[key]).strip()
            return bool(v) and v not in ("0", "false", "FALSE")
        return False

    def eval_cond(self, cond):
        """Evaluate a VPC condition expression. None/empty => True.

        Symbols must be resolved *as booleans* before any macro expansion.
        Expanding first is a trap: expand() has no entry for a symbol whose
        value is 0 (it is not a macro), so "$WINDOWS" became "" and every
        Windows-only branch evaluated true.
        """
        if cond is None:
            return True
        src = cond.strip()
        if not src:
            return True

        out = []
        pos = 0
        for m in _COND_TOKEN.finditer(src):
            if m.start() != pos:
                return False           # unparsable: stay conservative
            pos = m.end()
            name = m.group("paren") or m.group("dollar") or m.group("bare_name")
            if name is not None:
                out.append("t(%r)" % name.upper())
            elif m.group("kw"):
                out.append(m.group("kw"))
            elif m.group("ws"):
                pass
            else:
                out.append({"&&": " and ", "||": " or ", "!": " not ",
                            "(": " (", ")": ")"}[m.group("op")])
        if pos != len(src):
            return False
        try:
            return bool(eval("".join(out), {"t": self.truthy}))
        except Exception:
            return False


def config_applies(name, symbols):
    """FIX: named $Configuration blocks select on build type."""
    if not name:
        return True                                    # unnamed => always
    keys = CONFIG_NAMED.get(name.strip().upper())
    if keys is None:
        return True                                    # unknown name => apply
    return any(int(symbols.get(k, 0)) for k in keys)


