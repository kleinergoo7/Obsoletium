def norm_vpc_path(p, base_dir, root):
    p = p.replace("\\", "/").strip()
    if not p:
        return p
    if os.path.isabs(p):
        # Path macros like SRCDIR are pinned to absolute paths, so a resolved
        # "$SRCDIR\public" arrives absolute. Relativise it back to the source
        # root so emitted paths stay portable and greppable.
        p = os.path.normpath(p)
    else:
        p = os.path.normpath(os.path.join(base_dir, p))
    try:
        rel = os.path.relpath(p, root)
    except ValueError:
        return p.replace("\\", "/")
    if rel.startswith(".."):
        return p.replace("\\", "/")
    return rel.replace("\\", "/")


def target_name(name):
    """CMake/Ninja-safe target name for a VPC project name.

    VPC project names are human labels, not identifiers: "client (CStrike)",
    "VScript (SOB)", "dx_proxy ()", "remote-shader-compiler". Spaces and
    parentheses are legal in CMake target names but produce unusable Ninja
    edges and shell-quoting hazards, so fold them to '_'.
    """
    t = re.sub(r"[()\[\]{}]", "", name)
    t = re.sub(r"[^A-Za-z0-9_.+-]+", "_", t).strip("_")
    return t or "unnamed"


def norm_lib_name(raw):
    """'$SRCDIR/lib/public/tier0' or 'Advapi32.lib' -> a linkable target name."""
    p = raw.replace("\\", "/").strip()
    for ext in (".lib", ".a", ".so", ".dylib", ".link"):
        if p.lower().endswith(ext):
            p = p[: -len(ext)]
            break
    base = os.path.basename(p.rstrip("/"))
    if base.lower().startswith("lib"):
        cand = base[3:]
        if cand:
            base = cand
    return base


