def build_symbols(sets):
    symbols = dict(PLATFORM_DEFAULTS)
    for kv in sets:
        k, _, v = kv.partition("=")
        symbols[k.upper()] = int(v) if v.strip().lstrip("-").isdigit() else (1 if v else 0)
    return symbols


def _all_vpc(root):
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        # The repo root also holds non-engine trees (reference clone, game
        # assets, generated run tree, build output, scratch); their .vpc files
        # are not part of this build.
        dirnames[:] = [d for d in dirnames
                       if d not in (".git", ".git-obsolete-backup", "build",
                                    "build-client", "build-asan",
                                    "build-client-gl", "cmake", "research",
                                    "css-steam-assets", "game_client", "game-run",
                                    "logs", "__tmp", "node_modules")]
        for f in filenames:
            if f.endswith(".vpc"):
                out.append(os.path.join(dirpath, f))
    return sorted(out)


def audit(mods, missing):
    print(f"{'module':<26} {'src':>5} {'inc':>4} {'def':>4} {'lib':>4} {'sys':>4}  "
          f"{'kind':<16} vpc")
    print("-" * 110)
    for name, m in mods.items():
        st = m.settings
        kind = (st.config_type or ("library" if st.is_lib else "app"))[:16]
        print(f"{name:<26} {len(set(st.sources)):>5} {len(set(st.includes)):>4} "
              f"{len(set(st.defines)):>4} {len(set(st.libs)):>4} "
              f"{len(set(st.system_libs)):>4}  {kind:<16} {m.path}")
    tot = sum(len(set(m.settings.sources)) for m in mods.values())
    print("-" * 110)
    print(f"modules: {len(mods)}   unique sources: {tot}")
    uniq = sorted(set(missing))
    if uniq:
        print(f"unresolved macros ({len(uniq)}): {', '.join(uniq[:40])}")
    dropped = sorted({l for m in mods.values() for l in m.settings.dropped_libs})
    if dropped:
        print(f"dropped libs ({len(dropped)}): {', '.join(dropped[:10])}")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", required=True, help="engine source root")
    ap.add_argument("--out", help="output dir for generated cmake/json")
    ap.add_argument("--dump", help="parse a single .vpc and print the model")
    ap.add_argument("--list", action="store_true", help="list all .vpc files")
    ap.add_argument("--audit", action="store_true",
                    help="print a per-module summary without writing files")
    ap.add_argument("--set", action="append", default=[], metavar="SYM=VAL",
                    help="override a platform symbol, e.g. DEDICATED=1")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    symbols = build_symbols(args.set)

    if args.list:
        for p in sorted(_all_vpc(root)):
            print(os.path.relpath(p, root))
        return 0

    if args.dump:
        modules, glob, base_links, ctx = parse_vpc(os.path.abspath(args.dump),
                                                   symbols, root)
        print(f"// globals from $Configuration: "
              f"{len(glob.defines)} defines, {len(glob.includes)} includes, "
              f"{len(glob.system_libs)} system libs")
        print(f"// base link template (nameless $Project): "
              f"{base_links.libs + base_links.system_libs}")
        for m in modules:
            print(json.dumps(m.to_dict(), indent=2))
        if ctx and ctx.missing_macros:
            print(f"// unresolved macros: {', '.join(sorted(set(ctx.missing_macros)))}",
                  file=sys.stderr)
        return 0

    if not args.out and not args.audit:
        ap.error("--out is required unless --dump/--list/--audit is used")

    missing = []
    by_name = OrderedDict()
    for vpc in _all_vpc(root):
        modules, glob, base_links, ctx = parse_vpc(vpc, symbols, root)
        if ctx:
            missing.extend(ctx.missing_macros)
        for m in modules:
            prev = by_name.get(m.name)
            if prev is None:
                by_name[m.name] = m
                continue
            # A .vpc may be reachable through several includes; merge, do not drop.
            for key in ("sources", "includes", "defines", "libs", "system_libs",
                        "dynamic", "headers", "flags", "dropped_libs"):
                for v in getattr(m.settings, key):
                    prev.settings.add_unique(getattr(prev.settings, key), v)
            for ext, lst in m.settings.ignored.items():
                for p in lst:
                    prev.settings.ignored.setdefault(ext, []).append(p)
            prev.settings.is_lib = prev.settings.is_lib or m.settings.is_lib
            if not prev.settings.pch_through:
                prev.settings.pch_through = m.settings.pch_through

    if args.audit:
        audit(by_name, missing)
        return 0

    os.makedirs(args.out, exist_ok=True)
    for name, m in by_name.items():
        emit_cmake(m, args.out)
        with open(os.path.join(args.out, f"{m.target}.json"), "w") as f:
            json.dump(m.to_dict(), f, indent=2)

    total = sum(len(set(m.settings.sources)) for m in by_name.values())
    print(f"modules: {len(by_name)}   sources: {total}   -> {args.out}")
    uniq = sorted(set(missing))
    if uniq:
        print(f"note: unresolved macros ({len(uniq)}): {', '.join(uniq[:40])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
