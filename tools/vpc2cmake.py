def collect_file_overrides(block, st, ctx, root, base):
    """Hoist a $File's nested $Configuration/$Compiler settings to target scope.

    VPC attaches these to a single $File, but CMake only has target-wide include
    directories and definitions. Adding them target-wide is a strict superset of
    what VPC asks for and is what the generated target needs to compile.
    """
    for d in block:
        if d.name in ("Configuration", "Compiler", "General"):
            if d.block:
                collect_file_overrides(d.block, st, ctx, root, base)
            continue
        if d.name not in ("AdditionalIncludeDirectories",
                          "PreprocessorDefinitions"):
            continue
        for raw in d.active(ctx):
            if not raw or raw.startswith("["):
                continue
            # Same expansion and splitting the project-level handler uses: VPC
            # writes these as a single quoted "a;b" argument, and macro values may
            # themselves expand to several ';'-separated entries.
            for piece in re.split(r"[;,\s]+", ctx.expand(raw)):
                if not piece or piece == "$BASE":
                    continue
                if d.name == "PreprocessorDefinitions":
                    if "%(" in piece or LIBC_REDIRECT_DEFINE_RE.match(piece):
                        continue
                    st.add_unique(st.defines, piece)
                else:
                    st.add_unique(
                        st.includes, norm_vpc_path(piece, base, root))


def collect_settings(block, st, ctx, root, base, is_lib_project):
    """Fold a $Configuration or $Project body into `st`."""
    for d in block or []:
        n = d.name
        if d.excluded:
            # '$-' is VPC's removal idiom, not a comment: "-$File F" removes
            # F from the project. Per-mod .vpc files use it to drop base
            # sources they replace (client_cstrike.vpc drops
            # weapon_parse_default.cpp from client_base.vpc, whose
            # CreateWeaponInfo() collides with cs_weapon_parse.cpp's).
            # Skipping the directive instead of removing left both TUs in
            # libclient_CStrike.so and the link failed on the duplicate.
            if n in ("File", "DynamicFile") and ctx.eval_cond(d.cond):
                for raw in d.active(ctx):
                    if not raw or raw.startswith("["):
                        continue
                    p = norm_vpc_path(ctx.expand(raw), base, root)
                    if not p:
                        continue
                    for seq in (st.sources, st.dynamic, st.headers):
                        while p in seq:
                            seq.remove(p)
            continue
        if not ctx.eval_cond(d.cond):
            continue
        values = d.active(ctx)

        if n in ("General", "Compiler", "Linker", "CustomBuildStep",
                 "PostBuildEvent", "Configuration", "Folder", "Project"):
            collect_settings(d.block, st, ctx, root, base, is_lib_project)

        elif n in ("File", "DynamicFile"):
            for raw in values:
                if not raw or raw.startswith("["):
                    continue
                p = norm_vpc_path(ctx.expand(raw), base, root)
                if not p:
                    continue
                ext = os.path.splitext(p)[1]
                if n == "DynamicFile":
                    st.add_unique(st.dynamic, p)
                elif ext in SOURCE_EXTS:
                    st.add_unique(st.sources, p)
                elif ext in IGNORED_EXTS:
                    st.ignored.setdefault(ext, []).append(p)
                else:
                    st.ignored.setdefault(ext or "<none>", []).append(p)
            # Per-file configuration block. PCH selection is still ignored (CMake
            # gets that from target_precompile_headers()), but the per-file
            # $AdditionalIncludeDirectories and $PreprocessorDefinitions have to
            # be hoisted to target scope: CMake has no per-source-file include
            # path. vscript/vscript.vpc relies on this -- vlua.cpp includes
            # lobject.h and friends, which live in the Lua *src* directory rather
            # than the *include* directory the project-level block lists, and the
            # block is attached to the $File. Dropping it made the whole vscript
            # module unbuildable ("lobject.h: Datei oder Verzeichnis nicht
            # gefunden"). Only once, not once per argument, so that a $File
            # listing several paths does not re-apply its nested block N times.
            if d.block:
                collect_file_overrides(d.block, st, ctx, root, base)

        elif n in ("ImpLib", "Lib", "LibExternal", "AdditionalDependencies",
                   "ImportLibrary"):
            for raw in values:
                if not raw or raw.startswith("["):
                    continue
                expanded = ctx.expand(raw).replace("\\", "/")
                if not expanded or expanded == "$BASE":
                    continue
                if expanded.lower().endswith(".link"):
                    st.add_unique(st.link_scripts, expanded)
                    continue
                if n == "AdditionalDependencies":
                    # "$BASE Advapi32.lib gdi32.lib" -- a mixed list, and VPC
                    # accepts "," as a separator here too.
                    for piece in re.split(r"[;,\s]+", expanded):
                        if piece and piece != "$BASE":
                            _add_lib(st, piece, n)
                    continue
                if "$" in expanded:
                    # e.g. "$LIBPUBLIC\$_IMPLIB_PREFIX$OUTBINNAME$_IMPLIB_EXT"
                    # with LIBPUBLIC never defined. Basename-ing that would
                    # invent a library called "lib"; record and drop it.
                    ctx.missing_macros.append(expanded)
                    continue
                _add_lib(st, expanded, n)

        elif n == "SystemLibraries":
            for raw in values:
                if not raw or raw.startswith("["):
                    continue
                for piece in re.split(r"[;,\s]+", ctx.expand(raw)):
                    if piece and piece != "$BASE":
                        st.add_unique(st.system_libs, piece)

        elif n in ("PreprocessorDefinitions", "AdditionalIncludeDirectories",
                   "AdditionalLibraryDirectories"):
            for raw in values:
                if not raw or raw.startswith("["):
                    continue
                expanded = ctx.expand(raw)
                # VPC accepts ";" *and* "," here (panel_zoo.vpc uses ",").
                for piece in re.split(r"[;,\s]+", expanded):
                    # FIX: $BASE is the VPC inheritance token, not a value.
                    if not piece or piece == "$BASE":
                        continue
                    if n == "PreprocessorDefinitions":
                        # "%(PreprocessorDefinitions)" is MSVC's inheritance
                        # token. CMake refuses it on a compiler command line.
                        if "%(" in piece:
                            continue
                        # MSVC-style libc redirects, e.g. "strncpy=use_Q_strncpy_instead".
                        # They are command-line macros, so they are already active
                        # while libstdc++ headers are parsed; <cstring> and <cstdio>
                        # contain `using ::strncpy;` / `using ::sprintf;`, which then
                        # expand to undeclared names and every game target fails to
                        # build with "»strncpy« wurde nicht innerhalb von »::«
                        # deklariert". No translation unit in the tree defines the
                        # replacement names either, so the macros could only ever
                        # break the build; the safe V_* helpers are called directly.
                        if LIBC_REDIRECT_DEFINE_RE.match(piece):
                            continue
                        st.add_unique(st.defines, piece)
                    else:
                        st.add_unique(st.includes,
                                      norm_vpc_path(piece, base, root))

        elif n in ("AdditionalOptions", "GCC_ExtraCompilerFlags",
                   "GCC_ExtraLinkerFlags"):
            for raw in values:
                if raw and not raw.startswith("["):
                    expanded = ctx.expand(raw)
                    for piece in re.split(r"\s+", expanded):
                        if piece and piece != "$BASE":
                            st.add_unique(st.flags, piece)

        elif n == "OutputFile":
            if values:
                st.output_name = ctx.expand(values[0]).replace("\\", "/")
        elif n == "GameOutputFile":
            if values:
                st.game_output_file = ctx.expand(values[0]).replace("\\", "/")
        elif n == "ConfigurationType":
            if values:
                ct = ctx.expand(values[0]).lower()
                st.config_type = ct
        elif n == "CreateUsePCHThroughFile":
            if values:
                st.pch_through = ctx.expand(values[0])


def _add_lib(st, expanded, kind):
    """Classify one library reference; Windows prebuilts are dropped, not linked."""
    base = os.path.basename(expanded.rstrip("/"))
    name = norm_lib_name(expanded)
    if not name:
        return
    if WIN32_LIBS.match(name) or base.lower().endswith(".lib"):
        st.add_unique(st.dropped_libs, f"{kind}:{expanded}")
        return
    st.add_unique(st.libs, name)


def parse_vpc(path, symbols, root, seen=None, depth=0):
    """Parse one .vpc root. Returns (modules, globals, base_links, ctx).

    Fresh Context per root: macro definitions do not leak between .vpc files.
    $Include is walked in place, so an included script contributes both its
    macros and its $Configuration blocks to the including script's globals --
    which is how vpc_scripts/source_posix_base.vpc ends up defining the shared
    compiler flags for every module.
    """
    if seen is None:
        seen = set()
    real = os.path.realpath(path)
    if real in seen or depth > 24 or not os.path.isfile(real):
        return [], Settings(), Settings(), None
    seen.add(real)

    ctype, is_lib = detect_config_type(real, symbols, root)
    if is_lib is None:
        is_lib = False

    ctx = Context(symbols, root)
    ctx.macros["SRCDIR"] = os.path.dirname(real)
    ctx.symbols = dict(symbols)
    ctx.symbols["IS_LIB_PROJECT"] = 1 if is_lib else 0

    modules, glob, base_links = [], Settings(), Settings()
    walk_vpc_file(real, ctx, root, is_lib, seen, depth, modules, glob, base_links, ctype)
    return modules, glob, base_links, ctx


def walk_vpc_file(real, ctx, root, is_lib, seen, depth, modules, glob, base_links, ctype):
    """Process one .vpc file's directives, recursing through $Include."""
    base = os.path.dirname(real)
    text = strip_comments(open(real, encoding="utf-8", errors="replace").read())
    directives = RawParser(text, real).parse_block(False)

    # Pass A: this file's macros, so the conditionals in pass B see them.
    for d in directives:
        if d.name in ("Macro", "MacroRequired", "MacroRequiredAllowEmpty"):
            ctx.define_macro(d, base)

    # Pass B: configurations, includes and projects, in file order.
    for d in directives:
        n = d.name
        if d.excluded or n in ("Macro", "MacroRequired", "MacroRequiredAllowEmpty"):
            continue

        if n == "Configuration":
            if not ctx.eval_cond(d.cond):
                continue
            cname = d.active(ctx)[0] if d.active(ctx) else ""
            if config_applies(cname, ctx.symbols):
                collect_settings(d.block, glob, ctx, root, base, is_lib)

        elif n == "Include":
            if not ctx.eval_cond(d.cond):
                continue
            for inc in d.active(ctx):
                inc = ctx.expand(inc)
                if not inc:
                    continue
                ipath = norm_vpc_path(inc, base, root)
                if not ipath.startswith("/"):
                    ipath = os.path.join(root, ipath)
                if os.path.isfile(ipath):
                    ireal = os.path.realpath(ipath)
                    if ireal not in seen and depth + 1 <= 24:
                        seen.add(ireal)
                        walk_vpc_file(ireal, ctx, root, is_lib, seen, depth + 1,
                                      modules, glob, base_links, ctype)

        elif n == "Project":
            if not ctx.eval_cond(d.cond):
                continue
            pname = d.active(ctx)[0] if d.active(ctx) else ""
            if not pname.strip():
                # A nameless $Project is ambiguous in the VPC sources. Two
                # distinct idioms use it:
                #
                #   a) the trailing "$Project { $Folder "Link Libraries" {...} }"
                #      that every module .vpc ends with, which contributes the
                #      shared $Lib/$Link set and nothing else, and
                #   b) the "$Project { $Folder "Source Files" {...} ... }" in
                #      the shared base scripts -- game/server/server_base.vpc
                #      and game/client/client_base.vpc -- whose 800-odd sources
                #      belong to the *including* project, exactly as if they
                #      had been written inline.
                # Folding all of it into base_links honoured (a) and silently
                # dropped (b), so server_CStrike built 144 sources out of the
                # 1006 the .vpc lists and shipped without baseentity.cpp, and
                # dlopen of the game DLL failed on CBaseEntity::SetRefEHandle
                # and 1866 further undefined symbols.
                #
                # So split them: link entries keep going to base_links, and
                # sources (with the rest of the per-target settings) go to the
                # pre-project accumulator, which the next named $Project in the
                # same file merges in. That is precisely the "as if inline"
                # behaviour, and it is a no-op for idiom (a), which has no
                # sources.
                _tpl = Settings()
                collect_settings(d.block, _tpl, ctx, root, base, is_lib)
                for _k in ("libs", "system_libs", "dropped_libs",
                           "link_scripts"):
                    for _v in getattr(_tpl, _k):
                        base_links.add_unique(getattr(base_links, _k), _v)
                for _k in ("sources", "headers", "dynamic", "includes",
                           "defines", "flags"):
                    for _v in getattr(_tpl, _k):
                        glob.add_unique(getattr(glob, _k), _v)
                for _ext, _lst in _tpl.ignored.items():
                    for _p in _lst:
                        glob.ignored.setdefault(_ext, []).append(_p)
                if _tpl.pch_through and not glob.pch_through:
                    glob.pch_through = _tpl.pch_through
                if _tpl.output_name and not glob.output_name:
                    glob.output_name = _tpl.output_name
                if _tpl.game_output_file and not glob.game_output_file:
                    glob.game_output_file = _tpl.game_output_file
                continue
            pname = ctx.expand(pname).strip()
            ctx.define("ProjectName", pname)
            ctx.define("TargetName", pname)
            ctx.define("TargetFileName", pname)
            ctx.define("OUTBINNAME", pname)
            ctx.define("PROJECTNAME", pname)
            mod = Module(pname, os.path.relpath(real, root))
            mod.settings.merge_sources(glob)
            for key in ("includes", "defines", "libs", "system_libs",
                        "dropped_libs", "link_scripts", "flags"):
                for v in getattr(glob, key):
                    mod.settings.add_unique(getattr(mod.settings, key), v)
            if glob.pch_through:
                mod.settings.pch_through = glob.pch_through
            # A nameless $Project's link entries describe the *including*
            # module, so they belong to every named project in the same file
            # ("as if inline", exactly like the sources above). This used to be
            # gated on `if not is_lib`, which was meant to keep link
            # dependencies off static libraries -- but detect_config_type()
            # computes is_lib as `"library" in ctype.lower()`, so on Linux a
            # "Dynamic Library" is a library too and the gate swallowed the
            # link list of every shared module in the tree.
            #
            # server_CStrike is the loudest casualty: the only $Libs it has is
            # the trailing nameless $Project in game/server/server_base.vpc
            # (choreoobjects dmxloader mathlib particles tier2 tier3), so
            # libserver_CStrike.so ended up with DT_NEEDED = libvstdlib.so and
            # libtier0.so only, and ldd -r reported 225 undefined symbols --
            # 104 of them CChoreo* from the choreoobjects it never linked.
            # The same gate silently emptied client_CStrike's eleven-entry
            # base list, and it also made the $Lib cryptopp added to
            # vpc_scripts/source_cryptlib_include.vpc vanish, which is what
            # left libfilesystem_stdio.so and libdedicated.so failing to load
            # with:
            #   undefined symbol: _ZNK8CryptoPP21KeyDerivationFunction19MinDerivedKeyLengthEv
            #
            # Merging unconditionally is the VPC-faithful behaviour and is safe
            # for static libraries as well: CMake accepts target_link_libraries()
            # on them and simply records the dependency without archiving it.
            for v in base_links.libs:
                mod.settings.add_unique(mod.settings.libs, v)
            for v in base_links.system_libs:
                mod.settings.add_unique(mod.settings.system_libs, v)
            # Global blocks are collected before the project's own name is
            # known, so "DLLNAME=$OUTBINNAME" (OUTBINNAME -> $PROJECTNAME) is
            # still deferred. Resolve those now that ProjectName is set.
            for key in ("defines", "includes", "libs", "system_libs"):
                lst = getattr(mod.settings, key)
                for i, v in enumerate(lst):
                    if "$" in v:
                        lst[i] = ctx.expand(v)
            mod.settings.is_lib = is_lib
            mod.settings.config_type = ctype
            collect_settings(d.block, mod.settings, ctx, root, base, is_lib)
            modules.append(mod)


