def cmake_quote(s):
    """Quote a value for a CMake argument, or return None if unusable.

    A leftover '"' or an unexpanded "$NAME" means the .vpc text was malformed
    in a way we could not resolve; emitting it verbatim produces a confusing
    "Parse error. Function missing ending )" instead of a useful message.
    """
    if not s or "$" in s or '"' in s:
        return None
    return '"' + s.replace("\\", "/") + '"'


def cmake_list(items, indent="    "):
    if not items:
        return ""
    out, line = [], []
    for it in items:
        tok = cmake_quote(it)
        if tok is None:
            continue
        if line and len(line[-1]) + len(tok) + 1 > 100:
            out.append(" ".join(line))
            line = []
        line.append(tok)
    if line:
        out.append(" ".join(line))
    return ("\n" + indent).join(out)


def emit_cmake(mod, out_dir):
    st = mod.settings
    args = ["SOURCES" + ("\n" + cmake_list(st.sources) if st.sources else "")]
    for kw, vals in (("INCLUDES", sorted(set(st.includes))),
                      ("DEFINES", sorted(set(st.defines))),
                      ("LIBS", sorted(set(st.libs))),
                      ("SYSTEM_LIBS", sorted(set(st.system_libs))),
                      ("DYNAMIC", sorted(set(st.dynamic)))):
        if vals:
            args.append(kw + "\n" + cmake_list(vals))
    args.append("IS_LIB " + ("1" if st.is_lib else "0"))
    if st.pch_through:
        args.append(f'PCH "{st.pch_through}"')
    if st.output_name:
        args.append(f'OUTPUT "{st.output_name}"')
    if st.config_type:
        args.append(f'CONFIG_TYPE "{st.config_type}"')

    notes = []
    if st.dropped_libs:
        notes.append("dropped (Windows prebuilts / excluded): "
                     + ", ".join(sorted(set(st.dropped_libs))[:8]))
    if st.link_scripts:
        notes.append("link scripts needing a real link step: "
                     + ", ".join(sorted(set(st.link_scripts))))
    if st.flags:
        notes.append("raw flags for review: " + " ".join(sorted(set(st.flags))[:16]))

    txt = (f"# Generated by tools/vpc2cmake.py from {mod.path}\n"
           f"# Do not edit by hand: edit the .vpc file and re-run the generator.\n"
           + "".join(f"# NOTE: {n}\n" for n in notes)
           + f"se_vpc_module({mod.target}\n    " + "\n    ".join(args) + "\n)\n")
    with open(os.path.join(out_dir, f"{mod.target}.cmake"), "w") as f:
        f.write(txt)
    return txt


