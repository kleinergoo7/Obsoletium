#!/usr/bin/env python3
"""
vpc2cmake -- extract Linux/CMake build descriptions from Valve Project Compiler
(.vpc) scripts.

Why this exists
---------------
Obsoletium ships no Linux build system: the repository contains exactly one
CMakeLists.txt, a 215-line skeleton with no add_subdirectory() calls, and CI
builds Windows/MSVC projects generated by VPC. The .vpc files are therefore the
only authoritative description of what belongs to each engine module -- which
sources, which include directories, which preprocessor defines, which libraries.

Rather than hand-maintaining ~70 CMakeLists.txt (a guaranteed rot mechanism),
we parse the .vpc files the upstream project already maintains and emit CMake
include fragments. Add a file to tier0.vpc on Linux and it shows up here.

Supported VPC subset (as used by Obsoletium)
--------------------------------------------
  $Macro / $MacroRequired / $MacroRequiredAllowEmpty
  $Include
  $Configuration ["Debug"|"Release"] { $General $Compiler $Linker ... }
  $Project ["name"] { $Folder { $File ... } $Lib $ImpLib $LibExternal ... }
  Conditions:  [SYM]  [!SYM]  [A && B]  [A || B]  [!A && $B]   (no parentheses)
  '$-' prefixed directives are exclusion-marked (honoured, never emitted).
  Per-file configuration blocks (PCH selection etc.) are parsed and ignored:
  CMake gets equivalent behaviour from target_precompile_headers().

VPC semantics that this implementation has to get right
------------------------------------------------------
1. *Conditions are the whole game.*  Nearly every line in a .vpc is guarded by
   [$WIN32] / [$LINUXALL] / [$LINUX64] / [$POSIX] / [!$IS_LIB_PROJECT]. If a
   condition is not evaluated, Windows sources and Windows system libraries
   (Advapi32, gdi32, ws2_32, Comctl32, Dwmapi) end up in a Linux target.
2. *A nameless $Project is a template, not a module.*  vpc_scripts/source_posix_base.vpc
   and every module .vpc end with `$Project { $Folder "Link Libraries" {...} }`.
   Those entries supply the shared link set for the real project in the same
   script. Emitting them as a module would create phantom targets.
3. *$BASE means "inherit from the base configuration".*  It appears as the
   first element of many $PreprocessorDefinitions lines. We merge every
   applicable configuration block and drop the token.
4. *Named configuration blocks select on build type.*  `$Configuration "Debug"`
   applies for a Debug build, `$Configuration "Release"` for anything else, an
   unnamed `$Configuration` always applies.
5. *Later $ConfigurationType wins, and the base script's default is a trap.*
   source_posix_base.vpc sets "Application (.exe)" for everybody, so library
  -ness must be resolved by an ordered walk of the $Include closure rather than
   by scanning for any library type anywhere.

Output
------
  cmake/generated/<project>.cmake   se_vpc_module(...) call
  cmake/generated/<project>.json    full parsed model (for inspection/debugging)
  --audit                            per-module summary table

Usage
-----
  tools/vpc2cmake.py --root obsoletium --out cmake/generated
  tools/vpc2cmake.py --root obsoletium --audit
  tools/vpc2cmake.py --dump obsoletium/tier0/tier0.vpc      # inspect one file
  tools/vpc2cmake.py --list                                # list all .vpc
"""

