class Directive:
    __slots__ = ("name", "value", "cond", "item_conds", "block", "file",
                 "line", "excluded")

    def __init__(self, name, value, cond, block, file, line, excluded=False,
                 item_conds=None):
        self.name = name          # canonical name, e.g. "File", "Macro"
        self.value = value        # list of raw argument strings
        self.cond = cond          # whole-directive condition text or None
        # Per-argument conditions, parallel to self.value. A VPC list written
        # across line continuations guards each item individually:
        #     $File  "a.cpp"   \
        #             "b.cpp" [!$DEDICATED]   \
        #             "c.cpp" [$DEDICATED]
        # so the guard cannot be hoisted onto the directive as a whole.
        self.item_conds = item_conds
        self.block = block        # list[Directive] or None
        self.file = file
        self.line = line
        self.excluded = excluded  # '$-' prefixed

    def active(self, ctx):
        """Arguments whose own condition holds, in order.

        Falling back to self.value keeps macro and other value-less directives
        behaving exactly as before.
        """
        if not self.item_conds:
            return self.value
        return [v for v, c in zip(self.value, self.item_conds)
                if c is None or ctx.eval_cond(c)]

    def __repr__(self):
        return f"<${self.name} {self.value} {('[%s]' % self.cond) if self.cond else ''}>"


def strip_comments(txt):
    """Remove // and /* */ comments, preserving string literals."""
    out = []
    i, n = 0, len(txt)
    while i < n:
        c = txt[i]
        if c == '"':
            j = i + 1
            while j < n:
                if txt[j] == "\\":
                    j += 2
                    continue
                if txt[j] == '"':
                    break
                j += 1
            out.append(txt[i:j + 1])
            i = j + 1
        elif c == "/" and i + 1 < n and txt[i + 1] == "/":
            while i < n and txt[i] != "\n":
                i += 1
        elif c == "/" and i + 1 < n and txt[i + 1] == "*":
            i += 2
            while i + 1 < n and not (txt[i] == "*" and txt[i + 1] == "/"):
                i += 1
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


TOKEN_RE = re.compile(r"""
    (?P<ws>\s+)
  | (?P<dir>-?\$-?[A-Za-z][A-Za-z0-9_/\-]*)
  | (?P<str>"(?:\\.|[^"\\\n])*")
  | (?P<cond>\[(?:[^\[\]]|\[[^\[\]]*\])*\]+)
  | (?P<lb>\{)
  | (?P<rb>\})
  | (?P<word>[^\s"\{\}\[\]]+)
""", re.VERBOSE)


class RawParser:
    """Turns .vpc text into a Directive tree.

    VPC is a loose language: arguments may be quoted strings, bare words
    (macro names, library names, MSVC flag strings), bracketed conditions, or a
    backslash-continued sequence of all of those. Whitespace is insignificant
    and must never terminate an argument list.
    """

    def __init__(self, text, filename):
        self.text = text
        self.file = filename
        self.toks = self._lex(text)

    @staticmethod
    def _lex(text):
        toks, i, n = [], 0, len(text)
        while i < n:
            m = TOKEN_RE.match(text, i)
            if not m:
                i += 1
                continue
            i = m.end()
            kind = m.lastgroup
            if kind == "ws":
                continue
            toks.append((kind, m.group(), 0))
        return toks

    def parse_block(self, stop_at_brace):
        """Parse directives until EOF or (optionally) a closing brace."""
        out = []
        while self.toks:
            kind, val, _ = self.toks[0]

            if kind == "rb":
                self.toks.pop(0)
                if stop_at_brace:
                    return out
                continue

            if kind == "lb":
                self.toks.pop(0)
                child = self.parse_block(True)
                if out and out[-1].block is None:
                    out[-1].block = child
                continue

            if kind == "dir":
                self.toks.pop(0)
                # Exclusion mark comes in both spellings: "-$File" (used by
                # every per-mod game .vpc) and "$-File".
                excluded = val.startswith("-$") or val.startswith("$-")
                name = canonical_name(val.lstrip("-$").lower())
                # FIX: conditions must land in d.cond, not in d.value[0].
                # Previously every Directive was built with cond=None while the
                # evaluators tested d.cond, so *no* condition was ever applied
                # and Windows sources leaked into the Linux build.
                value, cond, item_conds = self._read_args()
                d = Directive(name, value, cond, None, self.file, 0, excluded,
                              item_conds)
                out.append(d)
                if self.toks and self.toks[0][0] == "lb":
                    self.toks.pop(0)
                    d.block = self.parse_block(True)
                continue

            # Stray token with no directive owner: skip rather than abort.
            self.toks.pop(0)
        return out

    def _read_args(self):
        """Collect arguments up to '{' or the next directive.

        Returns (values, whole-directive condition, per-item conditions).

        A bracketed guard binds to the argument it follows, because a VPC list
        written across line continuations guards its items individually -- see
        engine/engine.vpc, where one $File group mixes [!$DEDICATED] and
        [$DEDICATED] files. Collecting the fragments and ANDing them together
        (which is what this used to do) makes such a group self-contradictory
        and drops every file in it: engine/engine.vpc lost cl_null.cpp, the
        dedicated server's null client stub, so the engine then referenced
        CBaseClient/CBaseClientState with no definition anywhere and dlopen of
        libengine.so failed with "undefined symbol:
        _ZN11CBaseClient13FireGameEventEP10IGameEvent".

        A guard seen before any argument is the only one that can apply to the
        directive as a whole, so it is returned separately.
        """
        value, item_conds, lead = [], [], []
        while self.toks:
            kind, val, _ = self.toks[0]
            if kind in ("lb", "rb", "dir"):
                break
            self.toks.pop(0)
            if kind == "str":
                value.append(unquote(val))
                item_conds.append(None)
            elif kind == "cond":
                c = val[1:-1].strip()
                if value:
                    item_conds[-1] = c       # guards the preceding argument
                elif c:
                    lead.append(c)
            else:  # word
                if val == "\\":
                    continue                      # line continuation marker
                if re.fullmatch(r'(\\[nrt"\\]|\s)+', val):
                    continue                      # escape sequence token
                value.append(val)
                item_conds.append(None)
        cond = " && ".join(lead) or None
        if len(value) == 1 and item_conds[0] is not None:
            # A single argument guarded by a trailing bracket is the directive's
            # own guard, not an item guard: "$Folder \"VGUI Panels\" [!$DEDICATED]"
            # has to keep suppressing the whole folder. Hoisting it also keeps
            # every scalar setting working unchanged.
            if item_conds[0]:
                cond = " && ".join(lead + [item_conds[0]]) or None
            item_conds = None
        elif not any(item_conds):
            item_conds = None
        return value, cond, item_conds


