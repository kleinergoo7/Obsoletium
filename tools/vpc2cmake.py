_CANON_CACHE = {}


def canonical_name(lower):
    # Hot path: called once per directive per parse, ~200k times per audit.
    hit = _CANON_CACHE.get(lower)
    if hit is not None:
        return hit
    if lower in CANON:
        result = CANON[lower]
    else:
        # Normalise: lower, drop non-alnum
        key = re.sub(r"[^a-z0-9]", "", lower)
        result = None
        for k, v in CANON.items():
            if re.sub(r"[^a-z0-9]", "", k) == key:
                result = v
                break
        if result is None:
            result = "".join(w.capitalize()
                             for w in re.split(r"[^a-z0-9]+", lower) if w)
    _CANON_CACHE[lower] = result
    return result


def unquote(s):
    s = s.strip()
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        s = s[1:-1]
    return s.replace("\\\\", "\\")


