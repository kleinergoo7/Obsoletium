#!/usr/bin/env python3
"""spv_embed.py -- emit a C++ header with uint32_t SPIR-V arrays.

Usage: spv_embed.py <out.h> <name1> <file1.spv> [<name2> <file2.spv> ...]
"""
import struct
import sys

out, pairs = sys.argv[1], sys.argv[2:]
assert len(pairs) % 2 == 0
with open(out, 'w') as f:
    f.write('// Generated by tools/spv_embed.py -- DO NOT EDIT.\n')
    f.write('#pragma once\n#include <cstddef>\n#include <cstdint>\n')
    for i in range(0, len(pairs), 2):
        name, path = pairs[i], pairs[i + 1]
        data = open(path, 'rb').read()
        assert len(data) % 4 == 0, path
        words = struct.unpack('<%dI' % (len(data) // 4), data)
        f.write('\nstatic const uint32_t %s[] = {\n' % name)
        for j in range(0, len(words), 6):
            f.write('    ' + ', '.join('0x%08xu' % w for w in words[j:j + 6]) + ',\n')
        f.write('};\nstatic const size_t %s_word_count = %d;\n' % (name, len(words)))
print('wrote %s' % out)
